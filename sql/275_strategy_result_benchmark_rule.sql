  FROM _benchmark_rule_version_map m
 WHERE r.result_version = m.old_version;

-- 3b. REFUSE AN UNMAPPED ROW. The literals above were generated against the
--     rows this migration's author could see. A database holding a pre-#2426
--     result row outside that set would have its `benchmark_rule` backfilled
--     here and its `result_version` left alone -- and from the next deploy
--     `_result_from_row` would raise on it forever, because the stored hash no
--     longer describes the completed payload.
--
--     After the two updates above, EVERY row must carry a mapped new version.
--     Anything else means the map was generated against a different database,
--     which is a condition to fail on loudly and inside the transaction, not to
--     discover later as an unreadable row.
DO $$
DECLARE
    unmapped INTEGER;
BEGIN
    SELECT count(*) INTO unmapped
      FROM strategy_results_store r
     WHERE NOT EXISTS (
               SELECT 1 FROM _benchmark_rule_version_map m
                WHERE m.new_version = r.result_version
           );
    IF unmapped > 0 THEN
        RAISE EXCEPTION
            '% result row(s) carry a result_version this migration has no mapping for. The version map was '
            'generated against a different database. Regenerate it with '
            '"PYTHONPATH=. uv run python scripts/verify_2426_benchmark.py --emit-version-map" and re-apply; '
            'leaving them would make every one of them unreadable through result_ledger._result_from_row.',
            unmapped
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
END $$;

-- 4. Now the column can carry its constraints. A BLANK value is PRESENT and
--    meaningless, and NOT NULL does not catch it -- the same check
--    `StrategyResult.__post_init__` makes in Python and `sql/256` makes for the
--    rule-set versions.
ALTER TABLE strategy_results_store
    ADD CONSTRAINT strategy_results_benchmark_rule_not_blank
    CHECK (btrim(benchmark_rule) <> '');

ALTER TABLE strategy_results_store
    ALTER COLUMN benchmark_rule SET NOT NULL;

-- 5. WARNING: `SELECT *` was expanded when the view was created, so a migration
--    adding a result column MUST re-run this statement (sql/264's own warning).
CREATE OR REPLACE VIEW strategy_results AS
    SELECT *
    FROM strategy_results_store
    WHERE namespace = 'in_sample';

-- WARNING: AND RE-APPLY THE CHECK OPTION, which `CREATE OR REPLACE VIEW` DROPS.
-- sql/264 sets it in a separate statement precisely because it cannot be carried
-- in the CREATE, and the consequence of forgetting it here is silent and exactly
-- backwards: the view stops refusing an INSERT that smuggles a `hold_out` row
-- through the in-sample name, which is criterion 5's whole mechanism. Caught by
-- `test_the_view_refuses_to_smuggle_a_hold_out_row`, not by review.
ALTER VIEW strategy_results SET (check_option = 'cascaded');

COMMIT;
