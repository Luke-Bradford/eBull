-- #2426 -- `benchmark_rule` joins the result identity, because the buy-and-hold
-- comparator had no rule of its own and silently inherited `sizing_rule`.
--
-- `equal_weight_concurrent_v1` re-imposes equal weight on every event date. A
-- comparator that rebalances is not buy-and-hold -- Blume & Stambaugh, "Biases
-- in computed returns: An application to the size effect", Journal of Financial
-- Economics 12 (1983), 387-404: rebalancing trades into the bid-ask noise in
-- each closing print, and "returns computed for buy-and-hold portfolios largely
-- avoid the bias induced by closing prices". They measure it at 0.056 percent
-- per day on the small-firm decile against 0.001 on the large-firm decile.
--
-- Measured on our own full population (2026-08-08, 5,266 legs over the whole
-- 16,236-date axis, identical legs and identical cost model under the two
-- compositions): the rebalanced form returns 1,204,631,084.15 percent against
-- the buy-and-hold form 3,223.24 -- 23.2 points of annual return, on a portfolio
-- that is supposed never to trade, having turned over 137,477,862x the pot.
-- Reproduce with:
--
--   PYTHONPATH=. uv run python scripts/verify_2426_benchmark.py --compositions
--
-- WHY THE STORED VERSIONS ARE RE-DERIVED, AND WHY THAT IS NOT A REWRITE OF
-- HISTORY. `ResultIdentity.version` hashes every input that determines a row's
-- numbers, and the benchmark rule always WAS such an input -- it just had no
-- name, so the hash was computed over an incomplete payload.
-- `result_ledger._result_from_row` re-derives that hash on every read and RAISES
-- on a mismatch, so adding the field without re-deriving would make all 24
-- existing rows permanently unreadable. `equal_weight_concurrent_v1` is
-- truthfully what produced them; re-deriving makes each row more accurate about
-- itself and preserves the only property that matters, that two runs differing
-- in the comparator get different versions.
--
-- The replacement hashes are LITERALS because a SQL-side re-implementation of
-- json.dumps(sort_keys=True, separators=(",", ":")) plus SHA-256 would have to
-- byte-match Python's, and a silent divergence there produces exactly the
-- unreadable rows this migration exists to avoid. Each was generated by
--
--   PYTHONPATH=. uv run python scripts/verify_2426_benchmark.py --emit-version-map
--
-- which asserts it reproduces the OLD hash from the stored columns before
-- emitting the new one.
--
-- WARNING: ORDER IS FORCED BY A TRIGGER. `trg_strategy_results_holdout_access`
-- fires BEFORE INSERT OR UPDATE and demands a `strategy_holdout_accesses` row
-- matching (strategy_id, strategy_version, result_version) for every `hold_out`
-- row. So the access rows move to the new version FIRST, same transaction.

BEGIN;

-- 1. The column, nullable, so the backfill has somewhere to land.
ALTER TABLE strategy_results_store
    ADD COLUMN IF NOT EXISTS benchmark_rule TEXT;

-- 2. Backfill. Every existing row was produced by the inherited sizing rule.
--    Runs BEFORE the version rewrite, so the trigger still matches on the
--    versions the access rows currently carry.
UPDATE strategy_results_store
   SET benchmark_rule = 'equal_weight_concurrent_v1'
 WHERE benchmark_rule IS NULL;

-- 3. The re-derived identities: access rows first, then the results.
